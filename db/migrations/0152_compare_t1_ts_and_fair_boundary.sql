-- 0152: 비교기가 **실제로 되감은 시각**을 기록하고, fair_compare 쪽 경계도 적는다.
-- (2026-08-11 2차 코드리뷰 반영. mig 0149 가 절반만 한 일을 마저 한다.)
--
-- ■ ① `dispatch_compare_shadow.t1_ts` — 판별자만으로는 되짚을 수 없었다
-- mig 0149 는 T1 의 **출처**(`t1_ver`)만 남기고 **값**은 안 남겼다. 그런데 이 표의 PK 는
-- `(qc, queuename, tos_ytno, tos_upd)` 이고 `tos_upd` 는 이제 **쓰지 않는 시각**이다. 결과:
--
--   - TOS 가 UPD_DT 를 밀 때마다 **같은 배차가 새 행으로 다시 들어온다**
--     (실측 30분: 454행 / 고유 (qc,queuename,tos_ytno) 251개 — 118개(47%)가 2행 이상, 최대 6행)
--   - 옛 판에서는 중복 행마다 T1 이 달라 "다른 순간의 관측"이었지만, 지금은 **전부 같은 순간**
--     으로 되감는데 결과는 서로 다르다(같은 키에서 our_ytno 최대 5종)
--   - 표에 T1 이 없어 **사후 중복 제거가 불가능**하고, 자주 갱신되는 배차가 그 횟수만큼 가중된다
--
-- `t1_ts` 를 남기면 `DISTINCT ON (qc,queuename,tos_ytno,t1_ts)` 로 되짚을 수 있다.
--
-- ■ ② `t1_ver` 의 뜻을 넓힌다 (0 = 폴백)
-- 코드가 `coalesce(yt_dis_ts, upd_ts)` 를 쓰는데 판별자는 리터럴 1 이었다 — 폴백이 떨어지면
-- 판별자가 거짓말을 한다. 이제 계산값이다: 1 = yt_dis_ts / **0 = upd_ts 로 폴백** / NULL = 경계 이전.
-- (현재 폴백은 실측 0건이다. mig 0148 프로브 370/370 · 라이브 배차행 78/78 채움.
--  ⚠"0건"은 지금까지 못 봤다는 뜻이지 일어날 수 없다는 뜻이 아니다 — 그래서 판별자를 둔다.)
--
-- ■ ③ fair_compare 두 표에 경계를 적는다
-- mig 0149 가 fair_compare 의 T1·정렬·15분 창을 전부 배차 시각 기준으로 바꿨는데 **그쪽 표에는
-- 아무 표시도 안 남겼다.** 모집단 단차가 실측된다(fair_compare_shadow.n 이 경계 직전 92~120/틱
-- → 직후 23~59/틱 — 단, 한산한 시간대 효과와 35분 자료로는 분리 못 했다. **단차 크기는 미확정,
-- 정의가 바뀐 사실은 확정**). savings_pct 는 21일 보관이라 3주간 섞인다.
-- 특히 `fair_compare_detail.dispatch_ts` 는 **중복 제거 키이자 시간 버킷 키**인데 의미가 조용히
-- 바뀌었고 COMMENT 가 아예 없었다.
--
-- 새 ver 컬럼 대신 COMMENT 로 경계만 적는다: 이 두 표는 틱 단위 집계라 행 단위 판별자를 붙여도
-- 과거 구간을 되살리지 못하고, 경계 시각(2026-08-11 16:12:33 KST = 07:12:33Z)이 하나뿐이라
-- `ts` 로 가를 수 있다.
--
-- 멱등.

ALTER TABLE dispatch_compare_shadow ADD COLUMN IF NOT EXISTS t1_ts timestamptz;

COMMENT ON COLUMN dispatch_compare_shadow.t1_ts IS
  '이 행이 트럭 위치를 실제로 되감은 시각(T1) — mig 0152. '
  '⚠PK 의 tos_upd 는 T1 이 아니다(중복 제거 토큰). TOS 가 UPD_DT 를 밀면 같은 배차가 새 행으로 '
  '다시 들어오므로(실측 47%가 2행 이상), 집계 전 DISTINCT ON (qc,queuename,tos_ytno,t1_ts) 로 '
  '되짚을 것. 2026-08-11 이전은 NULL.';

COMMENT ON COLUMN dispatch_compare_shadow.t1_ver IS
  '트럭 위치를 되감은 시각(T1)의 원천 판별자(mig 0149·0152 로 뜻 확장). '
  'NULL = upd_ts(2026-08-11 경계 이전) / 1 = yt_dis_ts(TOS 배차 시각 실물) / '
  '0 = yt_dis_ts 가 비어 upd_ts 로 폴백(현재 실측 0건). '
  '집계할 때 반드시 이 값으로 먼저 가를 것.';

COMMENT ON TABLE fair_compare_shadow IS
  '공정비교(같은 순간·같은 풀 재매칭) 틱 집계. '
  '⚠2026-08-11 07:12:33Z 경계로 **모집단 정의가 바뀌었다**(mig 0149): 그 전에는 15분 창을 '
  'upd_ts(행 마지막 갱신)로 잡아 배차는 오래됐는데 무관한 갱신으로 값만 밀린 행이 "방금 배차"로 '
  '들어왔고, 이후로는 yt_dis_ts(배차 시각 실물)로 잡는다. ts 로 가르지 않고 21일치를 한 번에 '
  '읽으면 두 정의가 섞인다.';

COMMENT ON COLUMN fair_compare_detail.dispatch_ts IS
  'TOS 배차 시각. 중복 제거 키이자 시간 버킷 키다. '
  '⚠2026-08-11 07:12:33Z 이전은 upd_ts(행 마지막 갱신 = 배차 시각의 상한), 이후는 '
  'yt_dis_ts(배차 시각 실물·mig 0149). 시간대별 분해를 경계 너머로 이으면 버킷 의미가 갈린다.';

-- ■ ④ 오라벨 정정 (같은 날 내가 만든 것)
-- ②를 처음 배포할 때 판별을 `t1_ts = tos_upd` 로 했다. 틀렸다 — mig 0148 실측이 두 값의 격차를
-- **중앙 0초 · 61.7%가 5초 이내**로 적어뒀다. 즉 "같다"는 폴백 신호가 아니라 정상적으로 흔한
-- 경우다. 내가 내 측정을 무시하고 층화 기준을 잘못 잡았다(이 저장소의 단골 실패 유형).
-- 지금은 원시 컬럼(`live_workpool.yt_dis_ts`)의 NULL 여부로 판별한다.
--
-- 그 사이 t1_ver=0 으로 잘못 찍힌 행을 되돌린다. **진짜 폴백은 0건**이라고 볼 근거:
-- mig 0148 프로브 370/370 채움 · 라이브 배차행 72/72 채움 — yt_dis_ts 가 빈 배차행을 아직
-- 한 건도 못 봤다. 창은 이 컬럼이 존재한 구간 전체이므로 두 번 돌려도 결과가 같다(멱등).
UPDATE dispatch_compare_shadow
   SET t1_ver = 1
 WHERE t1_ver = 0
   AND t1_ts IS NOT NULL
   AND t1_ts = tos_upd
   AND ts < '2026-08-11 08:06:44+00';   -- 정정 배포 시각(17:06:44 KST) 이전만.
