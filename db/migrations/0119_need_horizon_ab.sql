-- 0119: 지평 레버(NEED_HORIZON)를 A/B 하네스에 태운다.
--
-- ■ 무엇을 재려는가
-- Stage-2 는 버킷에 "크레인이 그 베이를 **시작**하는 시각"을 마감으로 준다. 그런데 우리가 보내는
-- 트럭이 담당하는 건 그 베이의 첫 번째 컨테이너가 아니라 더 뒤쪽이다. 그 차이를 메우라고 있는
-- 항이 `spread = (cap/2) * move_s` 인데, `cap` 이 크레인당 지평(기본 900초)에 묶여 있어 최대
-- 4무브(약 9분)까지밖에 안 밀린다.
--
-- 실측(2026-08-03, 보정이 정상 적용된 뒤):
--     적하 — 작업도달 예측 중앙 **+1,855초**(정상·과거인 경우 1.1%)
--            그런데 Stage-2 마감은 **+590초**
--            TOS 가 실제로 그 큐에 배송한 시각은 **+1,215초**
-- ⇒ 예측은 맞는데 마감이 예측을 안 쓰고 '베이 시작 + 짧은 보정'으로 만들어진다. 그래서 적하
--   실행가능률이 0% 로 고정된다(현장 크레인 기아는 8.9%).
--
-- ■ 왜 그냥 켜지 않고 A/B 인가
-- 지평을 넓히면 크레인 한 대가 더 많은 트럭을 흡수한다 = 트럭이 소수 크레인에 몰린다. 라이브에서
-- 켜고 재보니 트럭 수로 정규화한 크레인 커버리지가 **14.1% → 11.9%** 로 일관되게 줄었다.
-- 이득(마감 정합)은 아직 미측정이므로, 한쪽만 재고 채택하면 오늘 이미 두 번 당한 '교란된 측정'을
-- 세 번째로 반복하는 것이다.
--
-- ■ ⚠ 전제조건 — 이미 충족됐다
-- 앞서 레버를 켜고 잰 한 창에서 적하 실행가능률이 0.0% 로 나와 "지평은 효과 없다"로 읽혔는데,
-- 그건 교란이었다: 그때는 mig0115/0117 직후라 작업도달 보정이 부트스트랩 0 이었고(참값 +1,474초)
-- 베이 시작 시각 자체가 25분 일렀다. 어떤 지평도 도움이 될 수 없는 상태였다.
-- 지금은 보정이 채워져 라이브다(양하 +219 / 적하 +658초). 그래서 이제야 이 팔을 잴 수 있다.
--
-- ■ 하네스
-- 기존 출항 티어 A/B 와 같은 구조 — 30분 블록, 블록 번호를 splitmix64 로 해시해 팔 배정(단순
-- 교대가 아니라 30분 주기와 공명하는 외부 요인에 팔이 정렬되는 것을 피한다), 블록 앞 3분은
-- 워밍업으로 표시(anti-thrash 의 '직전 추천'이 틱을 넘어 이어지므로 팔 전환 직후는 서로 오염된다).
-- ⚠ **소금(salt)을 출항 티어와 다르게 쓴다.** 같은 소금이면 두 레버의 팔이 완전히 상관돼
--   서로의 효과를 분리할 수 없다.
--
-- ■ 판정에 쓸 지표 (팔별로 비교)
--   ① 마감 정합: (TOS 실제 배송시각 − 우리 마감) 중앙 → 0 에 가까울수록 좋다   ← 주 지표
--   ② feasible_crane 비율이 현장 기아율(8.9%)과 정합적인가
--   ③ 크레인 커버리지: 틱당 서비스 크레인 수 / 트럭 수                          ← 비용
--   ④ 솔버 규모(works_raw·n_works)와 틱 지연
-- ①이 개선되고 ③의 손실이 그보다 작을 때만 승격한다.
--
-- 멱등.

ALTER TABLE stage2_solver_shadow ADD COLUMN IF NOT EXISTS need_horizon_on boolean;

COMMENT ON COLUMN stage2_solver_shadow.need_horizon_on IS
  '이 틱에서 작업유형별 지평(NEED_HORIZON)이 켜져 있었나. NULL = 그 컬럼이 생기기 전 틱. '
  'stage2_match_shadow 는 같은 ts 를 공유하므로 ts 로 조인해 추천 단위로 팔을 가를 수 있다(mig 0119).';
