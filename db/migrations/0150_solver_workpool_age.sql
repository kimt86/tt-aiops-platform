-- 0150: 매칭이 **실제로 쓴 작업목록의 나이**를 틱마다 남긴다.
--
-- ■ 왜
-- mig 0149 사이클에서 배차 매칭 틱의 위상을 매분 :15 로 고정했다(작업목록 착지 :00~:02 직후).
-- 그 전제가 깨지는 길이 여럿이다:
--   - Oracle 조회가 느려 착지가 :15 를 넘긴다(같은 질의 소요 2~15초 관측)
--   - 누군가 tt-workpool.timer 의 초(:55)를 옮긴다
--   - 코드의 MATCH_TICK_SEC 만 바꾸고 타이머를 안 맞춘다
-- 깨지면 매칭은 **한 세대 낡은 목록**으로 돈다. 그때 나이는 ~75초인데,
-- **신선도 게이트 임계는 300초라 걸리지 않는다.** 경보도 로그도 남지 않고 추천 품질만 조용히
-- 떨어진다.
--
-- 이 사이클에 실제로 같은 유형의 일이 있었다: 비교기 T1 을 바꾸자 위치 이력 6분 창 밖으로
-- 나가 스냅샷 적중이 41% → 16% 로 떨어졌는데, **경보도 로그도 없었고 사람이 질의를 돌려서**
-- 찾았다. 조용한 퇴화는 재놓지 않으면 못 잡는다.
--
-- ■ 비용 0
-- 이 숫자는 신선도 게이트가 매 틱 **이미 조회하고 있고**, "300초 넘었나"만 보고 버리던 값이다.
-- 새 질의가 아니라 버리던 것을 담는 것이다.
--
-- ■ 읽는 법
--   정상 대역 = **15~16초** (매칭 위상 :15 − 착지 :00~:02).
--   60초대로 튀면 위상이 풀린 것 = 낡은 목록으로 추천이 나갔다는 뜻.
--   NULL = 신선도 조회 자체가 실패한 틱(그 틱은 낡음으로 판정돼 건너뛰므로 행이 안 남는 게
--          정상이나, 방어적으로 NULL 을 허용한다).
--   ⚠ 낡아서 건너뛴 틱은 행 자체가 없다 — 이 컬럼은 "매칭이 실제로 쓴 목록의 나이"만 담는다.
--   ⚠ 2026-08-11 이전 구간은 전부 NULL(그때는 안 재고 있었다). 위상도 그때는 고정이 아니었다.
--
-- 경보는 달지 않았다 — 임계를 정하려면 정상 대역이 며칠 쌓인 뒤에 보는 편이 맞다.
--
-- 멱등.

ALTER TABLE stage2_solver_shadow ADD COLUMN IF NOT EXISTS workpool_age_s integer;

COMMENT ON COLUMN stage2_solver_shadow.workpool_age_s IS
  '이 틱의 매칭이 실제로 쓴 작업목록의 나이(초) — data_freshness(WORKPOOL) 기준(mig 0150). '
  '정상 대역 15~16초(매칭 위상 :15 − 착지 :00~:02). 60초대로 튀면 위상이 풀려 '
  '한 세대 낡은 목록으로 추천이 나갔다는 뜻이다(300초 게이트에는 안 걸린다). '
  '2026-08-11 이전 구간은 NULL.';
