-- 0122: 배차 마감 판정을 **설계 ②**로 전환한다. 옛 식은 폐기.
--
-- ■ 설계 (사용자)
--   ① QC 작업 큐의 작업마다 예상 작업 시작 시각(크레인 기준)을 붙인다
--   ② 작업 종류별 트럭 준비시간(할당 후 QC 작업지점 도착까지)을 빼면 = **배차를 해야 할 시각**
--   ③ 그 시각으로 배차가 필요한 작업을 선정하고 후보 풀을 구성한다
--
-- ■ 옛 식이 무엇이었나 (폐기 대상)
--     마감 = max(크레인 시작 시각, 지금) + (크레인당 트럭 상한 ÷ 2) × 무브시간
--   준비시간을 **빼는** 게 아니라 상한의 절반을 **더했다**. 게다가 그 상한(NEED_HORIZON_S)은
--   원래 트럭을 여러 크레인에 흩뿌리려고 둔 값이라, 마감과 무관한 설정이 마감을 정하고 있었다.
--   실측(2026-08-03): 적하 기준 옛 마감 +2,627초 vs 설계 마감 +907초 — 옛 축이 28분 늦다.
--
-- ■ 전환 근거 (2026-08-04 07:30 예약 측정, 16시간·51,856행)
--   "그 큐에서 추천 시각 이후 처음 일어난 크레인↔트럭 핸드오버"를 정답으로 두고 절대오차 비교:
--     양하  옛 축 1,344초 → 새 축 **642초** (52.2% 개선)   · 위약(상수만 뺀 가짜 축) 953초
--     적하  옛 축 1,540초 → 새 축 1,508초 (2.1%)          · 위약 1,385초
--   양하는 세 시험(정확도·위약 대조·시간대 일관성) 전부 통과. 13개 시간대 전원 새 축 승.
--   ⚠ 적하는 셋 다 실패했다. 그 원인은 설계가 아니라 ①(크레인 도달 예측)이 상수로 붕괴한 것
--     (학습 보정이 +2,547초까지 커져 예측의 주항이 됐다 — 상수에서 상수를 빼면 또 상수라
--     위약과 구별되지 않는다). ①은 별건으로 남는다.
--   ⇒ 옛 식은 어느 쪽에서도 근거가 없으므로(설계상 틀렸고 실측에서도 진다) 폐기한다.
--
-- ■ 판정식 (전환 후)
--   마감      = work_eta_ts (크레인이 이 컨테이너를 다루는 시각). 더하는 항 없음.
--   여유      = 마감 − (지금 + 이 트럭의 p90 도착 + 안 세는 구간)
--   실행가능  = 여유 >= 0
--   여기서 "이 트럭의 p90 도착 + 안 세는 구간" 이 곧 설계 ②의 **트럭 준비시간**이다.
--   작업유형 평균 준비시간을 쓰는 버킷 단위 축은 dispatch_deadline_ts 로 따로 유지한다(mig 0120,
--   후보 풀 선정용).
--
-- ■ ⚠ 정의가 바뀌므로 판별자를 둔다
--   feasible / deadline_slack_s 는 19일치 시계열이 있고 보존이 21일이다. 같은 이름으로 정의를
--   바꾸면 두 의미가 구분자 없이 섞인다 — mig 0113 이 정확히 그 혼입으로 틀렸다.
--   그래서 컬럼은 재사용하되 **판(version)을 명시**한다:
--     deadline_ver = 1  옛 식(크레인 시작 + 상한÷2 × 무브시간). 2026-08-04 이전.
--     deadline_ver = 2  설계 ②. 이후.
--   집계·비교 시 반드시 이 값으로 가른다.
--
-- ■ crane_slack_s / feasible_crane (mig 0116) 는 어떻게 되나
--   전환 후 deadline_slack_s / feasible 과 **같은 값**이 된다. 지우지 않고 그대로 둔다 —
--   mig0116 시점부터 이미 새 정의로 기록돼 있어, 전환 이전 구간을 소급해 비교할 수 있는
--   유일한 계열이기 때문이다.
--
-- 멱등.

ALTER TABLE stage2_match_shadow ADD COLUMN IF NOT EXISTS deadline_ver smallint;

COMMENT ON COLUMN stage2_match_shadow.deadline_ver IS
  'deadline_slack_s / feasible 의 정의 판. '
  '1 = 옛 식(max(work_eta, now) + 크레인당상한÷2 × 무브시간). '
  '2 = 설계 ②(마감 = work_eta, 여유 = 마감 − (지금 + p90 도착 + 안 세는 구간)). '
  'NULL = 이 컬럼 이전. 집계 시 반드시 이 값으로 가를 것(mig 0122).';

COMMENT ON COLUMN stage2_match_shadow.deadline_slack_s IS
  'deadline_ver=2: 마감(work_eta) − (지금 + 이 트럭의 p90 도착 + 안 세는 구간). '
  'deadline_ver=1: 옛 식 기준(폐기). 두 판을 섞어 읽지 말 것.';
COMMENT ON COLUMN stage2_match_shadow.feasible IS
  'deadline_ver=2: deadline_slack_s >= 0. deadline_ver=1: 옛 식 기준(폐기).';
