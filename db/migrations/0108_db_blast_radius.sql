-- 0108: RAM 상한이 못 막는 DB 쪽 반경을 데이터베이스 기본값으로 못박는다.
--
-- 배경: 2026-07-28 OOM 장애 후 사용자 유닛 23개에 MemoryMax 를 걸었고(6cee359),
-- Postgres 컨테이너에도 -m 32g 를 걸었다(deploy/dev-db.sh). 그런데 컨테이너 메모리 상한은
-- **RAM** 만 막는다. 남는 반경 두 갈래는 디스크와 시간이다.
--
-- ⚠ statement_timeout 은 일부러 넣지 않는다. 이 프로젝트의 실제 실패 유형은 "느린 쿼리"가
--   아니라 "미검증 입력이 쓰기 행수를 정하는" 것이고, 그건 느리지 않다 — 손상 tier 하나가
--   만드는 10만행 INSERT 가 68ms 다(실측; 1천만행도 6.3초). 즉 시간 기반 방어로는 못 잡으면서
--   긴 백필 마이그레이션과 무거운 매뷰 리프레시는 죽일 수 있다. 순손해라 채택하지 않았다.
--   그 유형의 진짜 방어는 쓰기 지점의 물리 상한(mig0106 CHECK)과 크기·디스크 감시(mig0107)다.
--
-- 채택한 두 가지:
--
-- 1) temp_file_limit — 백엔드 하나가 정렬/해시 스필로 파일시스템을 채우는 것을 막는다.
--    근거(실측 2026-07-28): pg_stat_database 누적 temp_files=889 · temp_bytes=18GB ·
--    파일당 평균 20MB. 20GB 는 평균 스필의 1,000배이고, 평균의 100배짜리 이상치가 있어도
--    7배 여유다. 동시에 백엔드 하나가 디스크 여유(142GiB)를 혼자 못 먹는다.
--
-- 2) idle_in_transaction_session_timeout — 열린 채 방치된 트랜잭션이 vacuum 지평(backend_xmin)을
--    고정해 죽은 튜플이 안 지워지는 경로를 끊는다. 이건 조용한 디스크 증가라 07-28 유형과
--    증상이 같다(아무도 모르는 사이 자란다). 10분은 "작업 중"이 아니라 "놀고 있는" 시간이므로
--    긴 백필이라도 실제로 일하는 중이면 걸리지 않는다.
--
-- ROLE 이 아니라 DATABASE 에 건 이유: wp_ro 와 앞으로 생길 역할까지 함께 덮고, 슈퍼유저
-- 역할 자체는 건드리지 않는다. ⚠ 새 연결에만 적용된다 — 적용 후 tt-api 재시작이 필요하다
-- (상시 8개 풀 연결은 재시작 전까지 종전 값을 쓴다).
--
-- ⚠ 이건 강제가 아니라 기본값이다. 앱이 SUPERUSER 역할(wp)로 접속하므로 같은 세션이
--   SET 한 줄로 되돌릴 수 있다. 진짜 최소권한(앱 전용 비-슈퍼유저 역할)은 별개 과제다.
--
-- 멱등: ALTER DATABASE ... SET 은 같은 값으로 재실행해도 안전하다.

ALTER DATABASE wp_tt SET temp_file_limit = '20GB';
ALTER DATABASE wp_tt SET idle_in_transaction_session_timeout = '10min';
