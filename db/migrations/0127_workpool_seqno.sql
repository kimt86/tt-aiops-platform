-- 0127: 작업 목록에 TOS 의 **작업 순번(SEQNO)** 을 실어온다.
--
-- ■ 무엇이 문제였나
-- 구역 안에서 "이 상자가 몇 번째인가"(slot_idx)를 **지시 생성시각(cre_ts) 순**으로 매기고 있었다.
-- 채택 근거는 "생성순=처리순 82.5%(n=451)" 였는데, **재현되지 않는다**:
--   · 재검정            53.5%  (n=159)
--   · 예측 기반 시험    52~54% (n=38,443)  ← 같은 시험에서 적하는 76.4% 를 잡아낸다(양성 대조)
-- 즉 양하 순번은 사실상 동전 던지기였다. 그 결과 어느 상자든 실제보다 앞자리를 받아
-- 작업 도달 예측이 **예측 거리와 무관하게 일정하게 일렀다**(양하 +16~26분 · 적하 +37~39분).
--
-- ■ 왜 못 찾았나
-- `JOB_ODR_MSNSEQ`(순번처럼 보이는 칸)가 660건 전부 비어 있는 것을 보고 "TOS 에 순번이 없다"고
-- 단정했다. 실제로는 같은 표에 컬럼이 **92개** 있고 그중 우리가 뽑는 것은 20개뿐이며,
-- **`JOB_ODR_SEQNO` 는 채워져 있다**(미완료 지시 300/300). 저장소 문서에도 이미
-- "한 작업 = (CONTNO, POINT, SEQNO)" 라고 적혀 있었다(kc/data/tos-db-reference.html).
--
-- ■ SEQNO 가 무엇인가 (실측)
-- 배치 발행 시각 꼴의 문자열(`20260805070404`). 사전순 = 시간순이라 그대로 정렬하면 된다.
--   · ★동률의 뜻이 **열린 지시와 끝난 작업에서 다르다**(2026-08-05 배선 직후 실측):
--       끝난 작업 : 1개 75.9% · 2개 24.1% · 3개 이상 **0%**  → 2개짜리는 트윈(알려진 비율과 일치)
--       열린 지시 : 1개 53.7% · 2개 25.8% · **3개 이상 20.5%**(최대 26개)
--     ⇒ SEQNO 는 **배치로 발급됐다가 나중에 쪼개진다.** 사후 100% vs 사전 67~77% 의 차이는
--       "맞바꿈"보다 이 **미분화**로 더 잘 설명된다.
--     ⇒ 다만 slot_idx 는 row_number 라 동률에도 연속 번호를 준다. **개수는 보존되고**
--       블록 안 순서만 임의다(폴백 cre_ts → contno). 우리가 쓰는 것이 개수라 영향은 제한적이다.
--   · 사후(끝난 작업 298,074쌍): 처리 순서와 **100.0%** 일치.
--   · ⚠ 사전(미리 뜬 값으로 채점, n=232): **양하 76.6% · 적하 66.7%** — 위약(상자번호순) 53%.
--     ⇒ SEQNO 도 **개정된다**. 사후 100% 만 보고 채택했으면 st_ts·ETW 와 같은 함정에 빠졌다.
--   · 개정은 **국소적**이다: SEQNO 순위 차가 클수록 잘 맞는다(이웃 70.0% → 9자리 이상 82.8%).
--     선박 베이의 평평한 열은 순서가 무관해 맞바꿀 수 있다는 현장 설명과 맞는다.
--
-- ■ 그래서 왜 쓰나 — 우리에게 필요한 것은 순서가 아니라 **개수**다
-- "다음 상자 하나"를 찍는 것은 여전히 못 한다(구역 50곳 중 5곳, 10%). 그러나
-- "앞에 몇 개 있나"는 잘 맞는다. 사전 스냅샷 기준 실측(n=177/369, 창 하나·교대 걸침):
--     방식                     양하 치우침      적하 치우침
--     현행(목록 순번)          +16~26분 이름    +37~39분 이름
--     SEQNO 로 세기            +3.3분           −6.5분
--   계통 치우침이 사실상 사라지고 부호도 갈린다(남는 흩어짐 ±11.7 / ±6.8 자리).
--   ⚠ 두 방식을 완전히 같은 표본으로 잰 것은 아니다. 차이가 커서 방향은 분명하나
--     정확한 이득은 **라이브 그림자에서 다시 잰다**(이 마이그레이션의 목적).
--
-- ■ 이 마이그레이션이 하는 일
-- `live_workpool.seqno` 컬럼 추가. 추출기가 `JOB_ODR_SEQNO` 를 그대로 싣고, API 의 구역 안
-- 순번을 `cre_ts` 대신 이 값으로 매긴다. 값이 없으면 종전대로 `cre_ts` 로 떨어진다.
--
-- ⚠ 부하: `JOB_ODR_SEQNO` 는 이미 읽고 있는 행의 컬럼이므로 Oracle 조회 부하는 늘지 않는다.
-- ⚠ 타입: VARCHAR2 다. NUMBER 였다면 툴박스가 JSON 숫자로 바꿔 `Option<String>` 디코드가
--   배치째 실패했을 것이다(과거 실제 사고) — TO_CHAR 불필요.
-- ⚠ `cre_ts` 는 지우지 않는다. 폴백이자, 두 축을 나란히 비교할 유일한 계열이다.
--
-- 멱등.

ALTER TABLE live_workpool ADD COLUMN IF NOT EXISTS seqno text;

COMMENT ON COLUMN live_workpool.seqno IS
  'TOS JOB_ODR_SEQNO — 크레인 작업 순번(배치 발행 시각 꼴 문자열, 사전순=시간순). '
  '구역 안 순서의 권위 값. ⚠동률의 뜻이 다르다: 끝난 작업은 동률=트윈(최대 2개)이지만, '
  '열린 지시는 배치가 아직 안 쪼개져 최대 26개가 묶인다(3개 이상 20.5%). '
  '⚠ 개정된다: 사후 100% / 사전 67~77%(위약 53%). 개정은 국소적(가까운 자리끼리 맞바꿈). '
  '"다음 하나"를 찍는 데는 못 쓰고(10%), "앞에 몇 개"를 세는 데 쓴다. mig 0127.';

COMMENT ON COLUMN live_workpool.cre_ts IS
  '작업지시 생성 시각(CRE_DT). ★2026-08-05 부터 구역 안 순번의 **폴백**으로 강등 — '
  'seqno 가 없을 때만 쓴다. 단독 사용 시 처리순 일치율이 52~54% 로 동전 던지기였다(mig 0127).';
