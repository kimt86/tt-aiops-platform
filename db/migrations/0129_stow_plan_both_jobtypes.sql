-- 0129: 적부계획 수집을 **양하까지** 넓힌다. mig0128 의 "적하 전용"은 내 측정 오류였다.
--
-- ■ 무엇이 틀렸나
-- 0128 에서 "양하는 원천이 13.6% 만 채워져 있어 쓸 수 없다"고 적고 `DISLOAD='L'` 로 잘랐다.
-- 그 13.6% 는 **`VSP_SHP_PLANST` 조건을 안 걸고 센 값**이다. VSP_SHIP 의 양하 행에는 두 종류가
-- 섞여 있다:
--     PLANST='B'  배에 실려 있다고 신고된 것(BAPLIE). 아직 이번 항차의 작업 계획이 아니다 → 순번 없음
--     PLANST='P'  이번 항차에서 **할 일로 계획된 것**                                  → 순번 100%
-- 실측(항차 ANL8 006/2026, 미완료 행): 양하 B 1,017행 순번 0.0% · 양하 **P 627행 순번 100.0%** ·
-- 적하 P 1,220행 순번 100.0%. B 를 분모에 넣으니 13.6% 가 됐다.
--
-- ■ TOS 자신도 P 만 쓴다 (OSS 소스)
-- 양하 선택 질의 `selectDischargingJobListByQc` 는 VSP_SHIP 을 INNER JOIN 하며 `VSP_SHP_PLANST='P'`
-- 를 건다. 정렬도 적하와 **완전히 같다**:
--     RANK() OVER (PARTITION BY 크레인 ORDER BY JOB_QUE_PLND_DATE||TIME, VSP_SHP_PLANSEQ) … WHERE RN=1
-- (LoadableJob.xml:444,499 — 적하는 같은 파일 757행)
--
-- ■ 계획 행 수가 남은 일과 맞는다 (교차 검증)
--   ANL8 006/2026 — 계획 P: 양하 627 / 적하 1,220
--                   우리 큐 카운터 남은 일: 양하 630 / 적하 1,220
--   양하 3 차이는 그 사이 처리된 것으로 보인다. 즉 **P = 남은 일**이다.
--
-- ■ 알갱이도 같다
--   양하 구역 12곳 **전부**에서 순번이 상자를 완전히 구별한다(구역당 중앙 38상자 / 순번 38개).
--   적·양하 합쳐 실측하면 구역 164곳 중 164곳(100%).
--
-- ■ 부하 — ⚠ 0128 에 적은 "2.3초"를 정정한다
-- 그 값은 **단발 측정**이었다. 같은 조건으로 번갈아 3회씩 재면:
--     적하만        5.80 / 4.10 / 3.80  → 중앙 **4.10초**
--     적·양하 둘 다 5.80 / 6.61 / 6.00  → 중앙 **6.00초**
-- 넓혀서 +1.9초. 5분 주기이므로 시간당 Oracle 점유는 약 72초 — 워크풀(4.3초 × 40회 = 173초)보다
-- 가볍다. 편차가 커서(같은 질의가 4.2초와 15.2초) **단발 측정으로 판단하지 말 것**.
--
-- ■ 바뀌는 것
--   ① 질의 조건 `DISLOAD='L'` → `DISLOAD IN ('D','L') AND PLANST='P'`
--      (DISLOAD 를 명시해야 IDX_VSP_SHIP_VVCONT 의 선두 3컬럼을 그대로 탄다)
--   ② `live_stow_plan.disload` 컬럼 추가 — 구역 이름으로 유추하지 않고 값으로 구분한다
--   ③ 0128 의 "적하 전용" 주석 정정
--
-- 멱등.

ALTER TABLE live_stow_plan ADD COLUMN IF NOT EXISTS disload text;

COMMENT ON TABLE live_stow_plan IS
  '적부계획의 상자별 작업 순번(TOS VSP_SHIP, PLANST=''P'' 인 행만). 구역 안 순서의 권위 값 — '
  'TOS 배차기도 이것으로 정렬한다(LoadableJob.xml, 적하·양하 동일). **적하·양하 둘 다**(mig 0129 에서 '
  '0128 의 "적하 전용"을 정정 — 그 판단은 PLANST 조건을 빼고 센 오류였다). '
  '매 주기 전체 교체되는 스냅샷. 작업지시가 아직 없는 상자도 포함한다.';

COMMENT ON COLUMN live_stow_plan.disload IS
  'VSP_SHP_DISLOAD — ''D''=양하 · ''L''=적하. 구역 이름(38H-D 등)으로 유추하지 말고 이 값을 쓸 것.';

COMMENT ON COLUMN live_stow_plan.planseq IS
  'VSP_SHP_PLANSEQ — 구역 안 상자 순번. PLANST=''P'' 행에서는 적·양하 모두 100% 채워지고, '
  '실측상 구역 164곳 전부에서 상자를 완전히 구별한다(값 하나당 1상자). '
  '⚠ PLANST=''B''(BAPLIE 신고분)에는 없다 — 그 행을 분모에 넣으면 "양하는 13.6%뿐"이라는 오판이 나온다.';
